def main():
    flt = [a.lower() for a in sys.argv[1:]]
    cases = [c for c in CASES if not flt or any(f in c[0].lower() for f in flt)]
    client = TestClient(app)
    out = open("scripts/trap_report.txt", "w", encoding="utf-8")
    results = []  # (n, cat, q, mark, sec, found, cites, answer)
    t0 = time.perf_counter()
    print(f"Вопросов: {len(cases)}. LLM-ответы занимают 10-25 с, Ctrl+C прервёт и покажет итог.\n")
    try:
        for n, (cat, q, mode, kw, bad) in enumerate(cases, 1):
            t = time.perf_counter()
            try:
                r = client.post("/api/chat", json={"message": q})
                d = r.json()
            except Exception as e:  # noqa: BLE001
                r, d = None, {"detail": f"EXC {e}"}
            sec = time.perf_counter() - t
            ans = (d.get("answer") or d.get("detail") or "").strip()
            low = ans.lower()
            found = d.get("found")
            tags = ("[visa]" if d.get("visa") else "") + ("[clarify]" if d.get("clarify") else "")
            if r is None or r.status_code != 200:
                mark = "ERR"
            elif mode == "refuse":
                mark = "OK " if not found else "BAD"
            elif any(b in low for b in bad):
                mark = "BAD"
            elif not found and not tags:
                mark = "REF"  # отказал там, где ответ должен быть
            elif kw:
                mark = "OK " if any(k in low for k in kw) else "MISS"
            else:
                mark = "???"
            line = f"{n:3d} [{mark}] {cat:11s} {sec:5.1f}с {tags} | {q[:70]}"
            print(line)
            out.write(line + "\n   A: " + ans[:400].replace("\n", " ") + f"\n   пункты: {d.get('citations')}\n")
            out.flush()
            results.append((n, cat, q, mark.strip(), sec, found, d.get("citations"), ans))
    except KeyboardInterrupt:
        print("\nПрервано.")

    print("\n" + "=" * 70)
    print(f"Всего {time.perf_counter() - t0:.0f} с. Итог по категориям (OK / BAD / REF / MISS / ??? / ERR):")
    for cat in dict.fromkeys(x[1] for x in results):
        rs = [x[3] for x in results if x[1] == cat]
        print(f"  {cat:11s}", " ".join(f"{m}={rs.count(m)}" for m in ("OK", "BAD", "REF", "MISS", "???", "ERR") if rs.count(m)))
    print("\n--- ПРОБЛЕМЫ (BAD / REF / ERR / MISS), пришлите этот блок ---")
    for n, cat, q, mark, sec, found, cites, ans in results:
        if mark in ("BAD", "REF", "ERR", "MISS"):
            print(f"\n#{n} [{mark}] ({cat}) found={found} пункты={cites}\nQ: {q}\nA: {ans[:260]}")
    out.close()


main()