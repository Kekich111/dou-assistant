from __future__ import annotations

import re
from datetime import date

_DATE = re.compile(r"\s*(\d{1,2})[./](\d{1,2})[./](\d{4})\s*")


def _d(s: str | None) -> date | None:
    m = _DATE.fullmatch(s or "")
    try:
        return date(int(m[3]), int(m[2]), int(m[1])) if m else None
    except ValueError:
        return None


def T(key, label, question, example=None, **kw):
    return {"key": key, "label": label, "type": "text", "question": question, "example": example, **kw}


def D(key, label, question, example="15.11.2026", **kw):
    return {"key": key, "label": label, "type": "date", "question": question, "example": example, **kw}


def C(key, label, question, choices):
    return {"key": key, "label": label, "type": "choice", "question": question,
            "choices": [{"label": a, "value": b} for a, b in choices]}


