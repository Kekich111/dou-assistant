def _audit_check(answers: dict) -> list[str]:
    out = []
    a, b = _d(answers.get("date_from")), _d(answers.get("date_to"))
    if a and b and b < a:
        out.append("Дата окончания аудита раньше даты начала. Проверьте период.")
    r, p = _d(answers.get("report_date")), _d(answers.get("plan_date"))
    if b and r and r < b:
        out.append("Срок представления отчёта раньше окончания аудита.")
    if r and p and p < r:
        out.append("План мероприятий предлагается подготовить раньше отчёта. Проверьте сроки.")
    return out


